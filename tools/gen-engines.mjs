// Generates scripts/engines.ts — the actual game-engine logos, extracted from the Iconify
// `logos` collection (official brand marks) and `simple-icons`. Run:
//   node tools/gen-engines.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const logos = require('@iconify-json/logos/icons.json');
const simple = require('@iconify-json/simple-icons/icons.json');

// name -> [collection, icon id, key, label]. Icons keep their own colours (Godot blue, Unreal U…);
// monochrome ones inherit the chip's text colour via fill / currentColor.
const SOURCES = [
  ['unity', logos, 'unity', 'unity', 'Unity'],
  ['unreal', logos, 'unrealengine-icon', 'unreal', 'Unreal Engine'],
  ['godot', logos, 'godot-icon', 'godot', 'Godot'],
  ['source', simple, 'sourceengine', 'source', 'Source Engine'],
];
const KEY = { unity: 'unity', unreal: 'unreal engine', godot: 'godot', source: 'source engine' };

function extract(collection, id) {
  const icon = collection.icons[id];
  if (!icon) throw new Error(`icon not found: ${id}`);
  const w = icon.width ?? collection.width ?? 24;
  const h = icon.height ?? collection.height ?? 24;
  const left = icon.left ?? 0, top = icon.top ?? 0;
  return { viewBox: `${left} ${top} ${w} ${h}`, body: icon.body };
}

const entries = SOURCES.map(([id, collection, iconId, key, label]) => {
  const { viewBox, body } = extract(collection, iconId);
  return `  ${JSON.stringify(KEY[key])}: { key: ${JSON.stringify(key)}, label: ${JSON.stringify(label)}, viewBox: ${JSON.stringify(viewBox)}, body: ${JSON.stringify(body)} }`;
});

const out = `// Generated by tools/gen-engines.mjs from Iconify (\`logos\` + \`simple-icons\`) — the engines' actual
// logos. Do not edit by hand; re-run the generator after changing the engine list.
export interface EngineIcon { key: string; label: string; viewBox: string; body: string }
export const ENGINES: Record<string, EngineIcon> = {
${entries.join(',\n')}
};
export function engineIcon(name?: string): EngineIcon | null {
    if (!name) return null;
    return ENGINES[name.trim().toLowerCase()] ?? null;
}
`;

writeFileSync(path.join(root, 'scripts/engines.ts'), out);
console.log(`wrote scripts/engines.ts (${entries.length} engines: ${SOURCES.map(s => s[3]).join(', ')})`);
