// Generates scripts/lang-icons.ts — real brand logos for the language notches on project cards,
// from simple-icons (Font Awesome does not ship most of these). Run:
//   node tools/gen-lang-icons.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const simple = require('@iconify-json/simple-icons/icons.json');

// languageCode() output -> simple-icons id. GDScript has no icon of its own, so it borrows Godot's.
const ICONS = {
  typescript: 'typescript',
  javascript: 'javascript',
  cpp: 'cplusplus',
  c: 'c',
  csharp: 'csharp',
  python: 'python',
  gdscript: 'godotengine',
  rust: 'rust',
  wasm: 'webassembly',
  cmake: 'cmake',
};

const rows = Object.entries(ICONS).map(([key, id]) => {
  const icon = simple.icons[id];
  if (!icon) throw new Error(`simple-icons has no icon for ${id}`);
  const w = icon.width ?? simple.width ?? 24;
  const h = icon.height ?? simple.height ?? 24;
  return '  ' + JSON.stringify(key) + ': { viewBox: ' + JSON.stringify(`0 0 ${w} ${h}`) + ', body: ' + JSON.stringify(icon.body) + ' }';
});

const out = [
  '// Generated by tools/gen-lang-icons.mjs from simple-icons — real logos for the language notches.',
  '// Do not edit by hand; re-run the generator after changing the list.',
  'export interface LangIcon { viewBox: string; body: string }',
  'export const LANG_ICONS: Record<string, LangIcon> = {',
  rows.join(',\n'),
  '};',
  'export function langIcon(code: string): string {',
  '    const icon = LANG_ICONS[code];',
  '    return icon ? `<svg class="tag-icon" viewBox="${icon.viewBox}" aria-hidden="true">${icon.body}</svg>` : \'\';',
  '}',
  '',
].join('\n');

writeFileSync(path.join(root, 'scripts/lang-icons.ts'), out);
console.log('wrote scripts/lang-icons.ts (' + Object.keys(ICONS).join(', ') + ')');
