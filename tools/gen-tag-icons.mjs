// Generates scripts/tag-icons.ts — real brand logos for link tags whose brand Font Awesome does not
// ship (Gumroad). Sourced from simple-icons. Run:
//   node tools/gen-tag-icons.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const simple = require('@iconify-json/simple-icons/icons.json');

// Brand key -> simple-icons id. Add a row here when a link site's brand is not in Font Awesome.
const ICONS = { gumroad: 'gumroad' };

const rows = Object.entries(ICONS).map(([key, id]) => {
  const icon = simple.icons[id];
  if (!icon) throw new Error(`simple-icons has no icon for ${id}`);
  const w = icon.width ?? simple.width ?? 24;
  const h = icon.height ?? simple.height ?? 24;
  return '  ' + JSON.stringify(key) + ': { viewBox: ' + JSON.stringify(`0 0 ${w} ${h}`) + ', body: ' + JSON.stringify(icon.body) + ' }';
});

const out = [
  '// Generated by tools/gen-tag-icons.mjs from simple-icons — the brand logos Font Awesome lacks.',
  '// Do not edit by hand; re-run the generator after changing the icon list.',
  'export interface TagIcon { viewBox: string; body: string }',
  'export const TAG_ICONS: Record<string, TagIcon> = {',
  rows.join(',\n'),
  '};',
  'export function brandIcon(key: string): string {',
  '    const icon = TAG_ICONS[key];',
  '    return icon ? `<svg class="tag-icon" viewBox="${icon.viewBox}" aria-hidden="true">${icon.body}</svg>` : \'\';',
  '}',
  '',
].join('\n');

writeFileSync(path.join(root, 'scripts/tag-icons.ts'), out);
console.log('wrote scripts/tag-icons.ts (' + Object.keys(ICONS).join(', ') + ')');
