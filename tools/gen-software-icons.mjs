// Generates scripts/software-icons.ts — real logos for the modelling-software notches on 3D cards.
// Blender comes from simple-icons; Substance Painter from the @iconify-json/thesvg-color set.
// Run: node tools/gen-software-icons.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const simple = require('@iconify-json/simple-icons/icons.json');
const thesvg = require('@iconify-json/thesvg-color/icons.json');
const fileicons = require('@iconify-json/file-icons/icons.json');

const vb = (set, icon) => `0 0 ${icon.width ?? set.width ?? 24} ${icon.height ?? set.height ?? 24}`;
const recolour = (body) => body.replace(/fill="(?!currentColor)[^"]*"/g, 'fill="currentColor"');

// Blender — simple-icons ships it as a single currentColor path.
const blender = simple.icons.blender;
if (!blender) throw new Error('simple-icons has no blender icon');

// Substance Painter — theSVG ships the "Pt" mark on a coloured tile. Keep only the mark (the
// glyph path) and recolour it, so it reads as a monochrome icon on the notch like the others.
// theSVG ships each Substance app as a dark rounded tile with lime "Pt"/"Ds" letters. Keep the
// whole logo, in its real colours, so it reads as the app icon rather than bare letters.
const substanceLogo = (id) => {
  const icon = thesvg.icons[id];
  if (!icon) throw new Error(`thesvg-color has no ${id}`);
  const tile = icon.body.match(/<path fill="#1e3101" d="([^"]+)"/);
  const mark = icon.body.match(/<path fill="#99e83f" d="([^"]+)"/);
  if (!tile || !mark) throw new Error(`${id} logo paths not found`);
  return { viewBox: vb(thesvg, icon), body: `<path fill="#1e3101" d="${tile[1]}"/><path fill="#99e83f" d="${mark[1]}"/>` };
};

// ZBrush — only the file-icons set carries a ZBrush glyph (a monochrome currentColor mark).
const zb = fileicons.icons.zbrush;
if (!zb) throw new Error('file-icons has no zbrush icon');

const ICONS = {
  blender: { viewBox: vb(simple, blender), body: recolour(blender.body) },
  substancepainter: substanceLogo('substance-3d-painter'),
  substancedesigner: substanceLogo('substance-3d-designer'),
  zbrush: { viewBox: vb(fileicons, zb), body: recolour(zb.body) },
};

const rows = Object.entries(ICONS).map(([key, icon]) =>
  '  ' + JSON.stringify(key) + ': { viewBox: ' + JSON.stringify(icon.viewBox) + ', body: ' + JSON.stringify(icon.body) + ' }');

const out = [
  '// Generated by tools/gen-software-icons.mjs — real logos for the modelling-software notches.',
  '// Do not edit by hand; re-run the generator after changing the list.',
  'export interface SoftwareIcon { viewBox: string; body: string }',
  'export const SOFTWARE_ICONS: Record<string, SoftwareIcon> = {',
  rows.join(',\n'),
  '};',
  'export function softwareIcon(code: string): string {',
  '    const icon = SOFTWARE_ICONS[code];',
  '    return icon ? `<svg class="tag-icon" viewBox="${icon.viewBox}" aria-hidden="true">${icon.body}</svg>` : \'\';',
  '}',
  '',
].join('\n');

writeFileSync(path.join(root, 'scripts/software-icons.ts'), out);
console.log('wrote scripts/software-icons.ts (' + Object.keys(ICONS).join(', ') + ')');
